/** Holds the selected language; defaults to the device locale, persisted across restarts. */
class LanguageState(context: Context) {
    private val prefs: SharedPreferences =
        context.getSharedPreferences("shifa_session", Context.MODE_PRIVATE)

    private val _lang = mutableStateOf(load())
    val lang: Language by _lang

    private fun load(): Language {
        return when (prefs.getString("language", null)) {
            "ar" -> Language.AR
            "en" -> Language.EN
            else -> if (Locale.getDefault().language.equals("ar", true)) Language.AR else Language.EN
        }
    }

    val strings: Strings get() = if (lang == Language.AR) arStrings else enStrings
    val layoutDirection: LayoutDirection
        get() = if (lang == Language.AR) LayoutDirection.Rtl else LayoutDirection.Ltr

    fun setLang(l: Language) {
        _lang.value = l
        prefs.edit().putString("language", if (l == Language.AR) "ar" else "en").apply()
    }
}

